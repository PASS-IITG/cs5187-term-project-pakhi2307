import csv, glob, json, os, sys, collections
sys.path.insert(0, "src/agents")
from answer import parse_final, hard
CSV = os.path.expanduser("~/cs5187/benchmark_work/questions.csv")
gt = {r["id"]: r["ground_truth_function"] for r in csv.DictReader(open(CSV, encoding="utf-8"))}
qids = sorted(gt)
CONDS = ["NOCTX", "SYN-TOOL", "CT-TOOL", "SYN-TEXT", "CT-TEXT"]

def load(p):
    by = collections.defaultdict(list)
    for l in open(p, encoding="utf-8"):
        r = json.loads(l)
        o, probs = parse_final(r["final_text"])
        o = o if isinstance(o, dict) else {}
        by[(r["question_id"], r["condition"])].append(
            dict(ans=o.get("answer_function"), top3=o.get("top3") or [], valid=not hard(probs), r=r))
    return by

out = ["# Results summary (generated by src/eval/summary.py)", ""]
for p in sorted(glob.glob("results/runs_*.jsonl")):
    model = os.path.basename(p)[5:-6]
    by = load(p)
    flagged = [q for q in qids if sum(x["ans"] == gt[q] for x in by.get((q, "NOCTX"), [])) >= 2]
    out += [f"## {model}", "", "Cells are exact (answer in top 3), as correct/runs.", "",
            "| Q | ground truth | " + " | ".join(CONDS) + " |", "|---" * (len(CONDS) + 2) + "|"]
    for q in qids:
        cells = []
        for c in CONDS:
            L = by.get((q, c), [])
            if not L:
                cells.append("-"); continue
            ex = sum(x["ans"] == gt[q] for x in L); t3 = sum(gt[q] in x["top3"] for x in L)
            cells.append(f"{ex}/{len(L)} ({t3}/{len(L)})")
        out.append(f"| {q}{' (flagged)' if q in flagged else ''} | {gt[q]} | " + " | ".join(cells) + " |")
    def hit(q, c, top=False):
        return any((gt[q] in x["top3"]) if top else (x["ans"] == gt[q]) for x in by.get((q, c), []))
    for label, qs in (("All questions", qids), ("Excluding flagged", [q for q in qids if q not in flagged])):
        out.append("")
        out.append(f"{label} (n={len(qs)}): " + "; ".join(
            f"{c} exact {sum(hit(q, c) for q in qs)}, top3 {sum(hit(q, c, True) for q in qs)}" for c in CONDS[1:]))
    out += ["", "| condition | runs | valid JSON | forced_final | mean turns | mean tool calls | mean prompt tokens (summed over turns) | mean completion tokens | mean latency s |",
            "|---|---|---|---|---|---|---|---|---|"]
    for c in CONDS:
        V = [x for q in qids for x in by.get((q, c), [])]
        if not V:
            continue
        R = [x["r"] for x in V]
        m = lambda k: sum(r[k] for r in R) / len(R)
        out.append(f"| {c} | {len(R)} | {sum(x['valid'] for x in V)} | {sum(r['stopped_by'] == 'forced_final' for r in R)} | "
                   f"{m('turns'):.1f} | {m('tool_calls'):.1f} | {m('prompt_tokens'):.0f} | {m('completion_tokens'):.0f} | {m('latency_s'):.0f} |")
    out.append("")
out += ["Notes: 6 questions; one run per tool condition; NOCTX = 3 sampled repeats (temperature 0.7). A question is flagged if the",
        "no-context answer is exact in 2 of 3 repeats. Path verification is not included (final answer only). TEXT = graph_slice, budget ceiling 6,000 tokens (slices end below it unless cut)."]
open("results/summary.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out))
